CREATE TABLE IF NOT EXISTS backup_receipts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    public_id VARCHAR(48) NOT NULL,
    account_id BIGINT UNSIGNED NOT NULL,
    backup_job_id BIGINT UNSIGNED NULL,
    restore_job_id BIGINT UNSIGNED NULL,
    snapshot_id BIGINT UNSIGNED NULL,
    request_id VARCHAR(64) NOT NULL,
    operation VARCHAR(100) NOT NULL,
    result ENUM('success','failure','denied','ignored') NOT NULL,
    receipt_hash CHAR(64) NULL,
    metadata_json JSON NULL,
    created_at DATETIME NOT NULL,
    UNIQUE KEY uq_backup_receipt_public (public_id),
    KEY idx_backup_receipt_account_time (account_id, created_at),
    CONSTRAINT fk_backup_receipt_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_backup_receipt_backup_job FOREIGN KEY (backup_job_id) REFERENCES backup_jobs(id) ON DELETE SET NULL,
    CONSTRAINT fk_backup_receipt_restore_job FOREIGN KEY (restore_job_id) REFERENCES restore_jobs(id) ON DELETE SET NULL,
    CONSTRAINT fk_backup_receipt_snapshot FOREIGN KEY (snapshot_id) REFERENCES backup_snapshots(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS storage_observations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    account_id BIGINT UNSIGNED NOT NULL,
    target_type ENUM('pod','homeserver') NOT NULL,
    pod_deployment_id BIGINT UNSIGNED NULL,
    homeserver_device_id BIGINT UNSIGNED NULL,
    usage_bytes BIGINT UNSIGNED NOT NULL,
    allowance_bytes BIGINT UNSIGNED NOT NULL,
    utilization_percent DECIMAL(6,2) NOT NULL,
    observed_at DATETIME NOT NULL,
    KEY idx_storage_observation_account_time (account_id, observed_at),
    KEY idx_storage_observation_pod_time (pod_deployment_id, observed_at),
    KEY idx_storage_observation_homeserver_time (homeserver_device_id, observed_at),
    CONSTRAINT fk_storage_observation_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_storage_observation_pod FOREIGN KEY (pod_deployment_id) REFERENCES pod_deployments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_storage_observation_homeserver FOREIGN KEY (homeserver_device_id) REFERENCES homeserver_devices(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS storage_alerts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    public_id VARCHAR(48) NOT NULL,
    account_id BIGINT UNSIGNED NOT NULL,
    observation_id BIGINT UNSIGNED NOT NULL,
    severity ENUM('warning','critical') NOT NULL,
    status ENUM('open','acknowledged','resolved') NOT NULL DEFAULT 'open',
    threshold_percent DECIMAL(6,2) NOT NULL,
    opened_at DATETIME NOT NULL,
    acknowledged_at DATETIME NULL,
    resolved_at DATETIME NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    UNIQUE KEY uq_storage_alert_public (public_id),
    KEY idx_storage_alert_account_status (account_id, status),
    CONSTRAINT fk_storage_alert_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_storage_alert_observation FOREIGN KEY (observation_id) REFERENCES storage_observations(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
